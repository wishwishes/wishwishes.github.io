// ===== Update Quote every 5 minutes =====
let lastQuoteIndex = -1;
function updateQuote() {
    const now = new Date();
    // 5-min slot: 0-287 (288 slots per day), map to 0-23 (24 quotes)
    const totalMinutes = now.getHours() * 60 + now.getMinutes();
    const slot = Math.floor(totalMinutes / 5) % 24;
    if (slot === lastQuoteIndex) return; // no change needed
    lastQuoteIndex = slot;
    const quote = quotes[slot];
    const zhEl = document.getElementById('quote-bubble-text');
    const enEl = document.getElementById('quote-bubble-text-en');
    if (zhEl) {
        zhEl.textContent = quote.zh;
        zhEl.style.opacity = currentLang === 'zh' ? '1' : '0';
    }
    if (enEl) {
        enEl.textContent = quote.en;
        enEl.style.opacity = currentLang === 'en' ? '1' : '0';
    }
}

// ===== Real-time Clock =====
function updateClock() {
    const now = new Date();
    const hourEl = document.getElementById('quote-hour');
    if (!hourEl) return;
    const isZh = currentLang === 'zh';
    const y = now.getFullYear();
    const m = String(now.getMonth() + 1).padStart(2, '0');
    const d = String(now.getDate()).padStart(2, '0');
    const H = String(now.getHours()).padStart(2, '0');
    const M = String(now.getMinutes()).padStart(2, '0');
    const S = String(now.getSeconds()).padStart(2, '0');
    const weekDaysZh = ['日', '一', '二', '三', '四', '五', '六'];
    const weekDaysEn = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
    const w = isZh ? weekDaysZh[now.getDay()] : weekDaysEn[now.getDay()];
    if (isZh) {
        hourEl.textContent = y + '年' + m + '月' + d + '日 周' + w + ' ' + H + ':' + M + ':' + S;
    } else {
        hourEl.textContent = w + ' ' + m + '/' + d + '/' + y + ' ' + H + ':' + M + ':' + S;
    }
}

// ===== Check Quote Change (every 5 min) =====
function checkQuoteChange() {
    updateQuote();
}

// ===== Visitor Counter =====
function updateVisitorCount() {
    const countEl = document.getElementById('visitor-count');
    if (!countEl) return;

    const STORAGE_KEY = 'yy_visitor_counted';
    const API_NAMESPACE = 'wishwishes-personal-site';
    const API_KEY = 'visitor-counts';

    const alreadyCounted = sessionStorage.getItem(STORAGE_KEY);

    const url = alreadyCounted
        ? 'https://api.counterapi.dev/v1/' + API_NAMESPACE + '/' + API_KEY + '/up'
        : 'https://api.counterapi.dev/v1/' + API_NAMESPACE + '/' + API_KEY + '/up';

    fetch(url)
        .then(function(r) { return r.json(); })
        .then(function(data) {
            const count = data && data.count ? data.count : 0;
            countEl.textContent = count.toLocaleString();
            sessionStorage.setItem(STORAGE_KEY, '1');
        })
        .catch(function() {
            countEl.textContent = '—';
        });
}

// ===== Navbar Scroll Effect =====
function handleNavScroll() {
    const navbar = document.getElementById('navbar');
    if (window.scrollY > 50) { navbar.classList.add('scrolled'); } else { navbar.classList.remove('scrolled'); }
}

// ===== Mobile Menu =====
function toggleMobileMenu() {
    document.getElementById('mobileMenu').classList.toggle('active');
    document.getElementById('mobileMenuBtn').classList.toggle('active');
}

// ===== Smooth Scroll =====
function smoothScroll(targetId) {
    const target = document.querySelector(targetId);
    if (target) {
        const navHeight = document.getElementById('navbar').offsetHeight;
        const targetPosition = target.getBoundingClientRect().top + window.pageYOffset - navHeight;
        window.scrollTo({ top: targetPosition, behavior: 'smooth' });
    }
    const menu = document.getElementById('mobileMenu');
    const btn = document.getElementById('mobileMenuBtn');
    if (menu.classList.contains('active')) { menu.classList.remove('active'); btn.classList.remove('active'); }
}

// ===== Initialize =====
document.addEventListener('DOMContentLoaded', function() {
    // Initialize Lucide icons
    if (typeof lucide !== 'undefined') lucide.createIcons();

    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', function() { switchLang(this.dataset.lang); });
    });
    window.addEventListener('scroll', handleNavScroll);
    handleNavScroll();
    const mobileMenuBtn = document.getElementById('mobileMenuBtn');
    if (mobileMenuBtn) mobileMenuBtn.addEventListener('click', toggleMobileMenu);
    document.querySelectorAll('.nav-link, .mobile-link').forEach(link => {
        link.addEventListener('click', function(e) { e.preventDefault(); smoothScroll(this.getAttribute('href')); });
    });
    switchLang('zh');
    updateQuote();
    updateClock();
    updateVisitorCount();
    setInterval(updateClock, 1000);
    setInterval(checkQuoteChange, 5000);
});
